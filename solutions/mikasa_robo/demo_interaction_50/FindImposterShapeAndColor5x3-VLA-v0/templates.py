TALL_SHAPES = ("sphere", "cube")
CELL = 0.003


def _template(shape):
    return np.array([[1 if ch == "1" else 0 for ch in row] for row in TEMPLATES[shape]], dtype=np.int32)


def _decompose(P, max_parts=3):
    """Explain a merged blob (world points Nx3) as a few axis-aligned shape templates.
    Greedy: place the best-scoring template, remove its cells, repeat on the remainder."""
    tms = {s: _template(s) for s in SHAPES}
    o = P[:, :2].min(axis=0) - 13 * CELL
    ix = np.floor((P[:, 0] - o[0]) / CELL).astype(np.int64)
    iy = np.floor((P[:, 1] - o[1]) / CELL).astype(np.int64)
    nx, ny = int(ix.max()) + 14, int(iy.max()) + 14
    B = np.zeros((nx, ny), dtype=np.int32)
    Bt = np.zeros((nx, ny), dtype=np.int32)
    B[ix, iy] = 1
    tall = P[:, 2] > 0.034
    Bt[ix[tall], iy[tall]] = 1
    parts = []
    for _ in range(max_parts):
        if B.sum() < 45:
            break
        best = None
        for s in SHAPES:
            tm = tms[s]
            ts = float(tm.sum())
            for i in range(0, nx - 24 + 1):
                for j in range(0, ny - 24 + 1):
                    w = B[i:i + 24, j:j + 24]
                    inter = float((tm * w).sum())
                    if inter < 0.5 * ts:
                        continue
                    tin = float((tm * Bt[i:i + 24, j:j + 24]).sum())
                    sc = inter - 1.5 * (ts - inter)
                    if s in TALL_SHAPES:
                        if tin < 0.25 * ts:
                            sc -= ts
                    else:
                        sc -= 2.0 * tin
                    if best is None or sc > best[0]:
                        best = (sc, s, i, j, inter / ts)
        if best is None or best[0] < 0.12 * float(tms[best[1]].sum()):
            break
        sc, s, i, j, frac = best
        tm = tms[s]
        B[i:i + 24, j:j + 24] = B[i:i + 24, j:j + 24] * (1 - tm)
        Bt[i:i + 24, j:j + 24] = Bt[i:i + 24, j:j + 24] * (1 - tm)
        parts.append({"shape": s, "x": float(o[0] + (i + 12) * CELL), "y": float(o[1] + (j + 12) * CELL),
                      "score": float(sc), "frac": float(frac)})
    return parts, int(B.sum())


def _deepest_cells(G):
    """Cells of binary grid G that survive the most 4-neighbour erosions."""
    cur = G.astype(np.int32)
    last = cur
    for _ in range(30):
        if cur.sum() == 0:
            break
        last = cur
        p = np.pad(cur, 1)
        cur = p[1:-1, 1:-1] * p[:-2, 1:-1] * p[2:, 1:-1] * p[1:-1, :-2] * p[1:-1, 2:]
    return np.argwhere(last > 0)


def _template_touch_offset(shape):
    """(dx, dy) in metres from the template centre to its most interior cell nearest the centre."""
    cells = _deepest_cells(_template(shape))
    c = np.array([11.5, 11.5])
    d = np.linalg.norm(cells - c, axis=1)
    k = cells[int(np.argmin(d))]
    return float((k[0] - c[0]) * CELL), float((k[1] - c[1]) * CELL)


def _touch_point(P, cell=0.002):
    """Most interior point of the top surface of one object's world points (Nx3)."""
    z = P[:, 2]
    zt = float(np.percentile(z, 95))
    top = P[z > zt - 0.007]
    if len(top) < 5:
        top = P
    o = top[:, :2].min(axis=0) - 2 * cell
    ix = np.floor((top[:, 0] - o[0]) / cell).astype(np.int64)
    iy = np.floor((top[:, 1] - o[1]) / cell).astype(np.int64)
    G = np.zeros((int(ix.max()) + 3, int(iy.max()) + 3), dtype=np.int32)
    G[ix, iy] = 1
    # close single-cell holes from sampling gaps
    p = np.pad(G, 1)
    nb = p[:-2, 1:-1] + p[2:, 1:-1] + p[1:-1, :-2] + p[1:-1, 2:]
    G = np.maximum(G, (nb >= 3).astype(np.int32))
    cells = _deepest_cells(G)
    cen = np.array([(top[:, 0].mean() - o[0]) / cell, (top[:, 1].mean() - o[1]) / cell])
    d = np.linalg.norm(cells + 0.5 - cen, axis=1)
    k = cells[int(np.argmin(d))]
    return float(o[0] + (k[0] + 0.5) * cell), float(o[1] + (k[1] + 0.5) * cell), zt
